@dataclass(frozen=True)
class Platform:
    """One destination on the diagram; ``kind`` is None for a generic one."""

    label: str
    assisted: bool
    kind: AtsKind | None = None


@dataclass(frozen=True)
class Flavour:
    """Platforms that take a candidate the same way."""

    key: str
    title: str
    note: str
    platforms: tuple[Platform, ...]


def platform_label(kind: AtsKind) -> str:
    return _LABELS.get(kind.value, kind.value.capitalize())


def source_kinds() -> tuple[AtsKind, ...]:
    """Platform behind each discovery source (``linkedin_post`` → LinkedIn), in order."""
    kinds: list[AtsKind] = []
    for name in get_args(JobSourceName):
        raw = str(name)
        for candidate in (raw, raw.split("_", 1)[0]):
            try:
                kinds.append(AtsKind(candidate))
                break
            except ValueError:
                continue
    return tuple(dict.fromkeys(kinds))


def _assisted_kinds() -> frozenset[AtsKind]:
    """Registry adapters, plus apply routes the adapters own themselves (email)."""
    routes = {method.value for method in ApplyMethod} - {ApplyMethod.UNKNOWN.value}
    return supported_kinds() | {kind for kind in AtsKind if kind.value in routes}


def _spoken_list(labels: Sequence[str]) -> str:
    if len(labels) < 2:
        return "".join(labels)
    return f"{', '.join(labels[:-1])} y {labels[-1]}"


def platform_flavours() -> tuple[Flavour, ...]:
    """Every known platform in exactly one group, read from the code that serves it."""
    assisted = _assisted_kinds()

    def group(kinds: Iterable[AtsKind]) -> tuple[Platform, ...]:
        return tuple(Platform(platform_label(k), k in assisted, k) for k in kinds)

    known = [kind for kind in AtsKind if kind is not AtsKind.UNKNOWN]
    ats = [kind for kind in known if kind not in JOB_BOARD_KINDS and kind is not AtsKind.EMAIL]

    def ats_needing(need: AccountNeed) -> tuple[Platform, ...]:
        return group(kind for kind in ats if account_need(kind) is need)

    sources = source_kinds()
    boards = [*sources, *(k for k in known if k in JOB_BOARD_KINDS and k not in sources)]
    searched = _spoken_list([platform_label(kind) for kind in sources])
    markers = len(html_marker_kinds())
    return (
        Flavour(
            "ats_open",
            "ATS sin cuenta",
            "Postulas directo en el formulario de cada empresa.",
            ats_needing(AccountNeed.NOT_NEEDED),
        ),
        Flavour(
            "ats_account",
            "ATS con cuenta por empresa",
            "Cada empresa abre su propia cuenta: la contraseña la pones tú.",
            ats_needing(AccountNeed.NEEDED),
        ),
        Flavour(
            "ats_unknown",
            "Otros ATS reconocidos",
            "Si piden cuenta se confirma al entrar; nada se da por hecho.",
            ats_needing(AccountNeed.UNKNOWN),
        ),
        Flavour(
            "boards",
            "Portales permanentes y job boards",
            f"Tu perfil al día; búsqueda de ofertas en {searched}.",
            group(boards),
        ),
        Flavour(
            "own_sites",
            "Sitios propios de empresas",
            f"Se reconoce el ATS que cargan por dentro: {markers} plataformas "
            "por marcador técnico.",
            (Platform("Página de empleo propia", False),),
        ),
        Flavour(
            "email",
            "Postulación por email",
            "Borrador en Gmail con tu CV adjunto; el envío es tuyo.",
            group([AtsKind.EMAIL]),
        ),
    )


