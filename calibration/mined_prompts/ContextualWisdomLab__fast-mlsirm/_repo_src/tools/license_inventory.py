class SpdxError(ValueError):
    """Raised for an expression outside the supported SPDX grammar or id list."""


class EvidenceReadError(OSError):
    """Raised when artifact bytes cannot be bound to one stable source path."""


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_stable_bytes(path: Path) -> bytes:
    """Read a regular file once and reject path or descriptor mutation."""
    before = path.lstat()
    if not stat.S_ISREG(before.st_mode):
        raise EvidenceReadError(f"artifact path is not a regular non-symlink file: {path}")
    with path.open("rb") as handle:
        opened = os.fstat(handle.fileno())
        if (before.st_dev, before.st_ino) != (opened.st_dev, opened.st_ino):
            raise EvidenceReadError(f"artifact path changed before read: {path}")
        data = handle.read()
        after_fd = os.fstat(handle.fileno())
    after_path = path.lstat()
    def identity(file_stat):
        return (file_stat.st_dev, file_stat.st_ino, file_stat.st_size, file_stat.st_mtime_ns)
    if identity(before) != identity(opened) or identity(opened) != identity(after_fd):
        raise EvidenceReadError(f"artifact changed while being read: {path}")
    if identity(after_fd) != identity(after_path):
        raise EvidenceReadError(f"artifact path was replaced after read: {path}")
    if len(data) != after_fd.st_size:
        raise EvidenceReadError(f"artifact read was incomplete: {path}")
    return data


def detect(text: str) -> list[str]:
    text = " ".join(text.split()).casefold()
    found = []
    for label, needles in TEXT_FINGERPRINTS:
        folded_needles = tuple(n.casefold() for n in needles)
        markers = FULL_TEXT_MARKERS.get(label)
        valid_standard_text = markers is None or all(marker in text for marker in markers)
        # Negating/conditional language may void a permissive grant, but it
        # never removes copyleft evidence: GPL-3.0 itself says a clause "does
        # not apply", and dropping the label would hide the copyleft component.
        copyleft = label in COPYLEFT_TEXT_LABELS + WEAK_COPYLEFT_TEXT_LABELS
        unqualified = copyleft or not any(marker in text for marker in NEGATING_OR_CONDITIONAL_MARKERS)
        if any(n in text for n in folded_needles) and valid_standard_text and unqualified:
            if label == "Apache-2.0" and "Apache-2.0 WITH LLVM-exception" in found:
                continue
            found.append(label)
    if "BSD" in found:
        found[found.index("BSD")] = "BSD-3-Clause" if "neither the name" in text else "BSD-2-Clause"
    return found


